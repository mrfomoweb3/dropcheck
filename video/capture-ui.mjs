import {fileURLToPath} from 'node:url';
import puppeteer from 'puppeteer-core';
import {writeFile} from 'node:fs/promises';
const dir = fileURLToPath(new URL('./dropcheck-film/assets/', import.meta.url));
const browser=await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const p=await browser.newPage(); await p.setViewport({width:1440,height:1000,deviceScaleFactor:2});
await p.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'reduce'}]);
await p.goto('http://localhost:8770/',{waitUntil:'networkidle2'});await p.screenshot({path:dir+'landing.png'});
await p.goto('http://localhost:8770/app/',{waitUntil:'networkidle2'});
await p.waitForFunction(()=>document.body.innerText.includes('Checked against live chain state'),{timeout:180000});
await p.waitForFunction(()=>!document.body.innerText.includes('Still reading'),{timeout:180000});
await p.screenshot({path:dir+'workspace.png'});
await p.evaluate(()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='Clear').click());await p.screenshot({path:dir+'empty.png'});
await p.evaluate(()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='Load demo list').click());
await p.waitForFunction(()=>document.body.innerText.includes('Checked against live chain state'),{timeout:180000});
await p.screenshot({path:dir+'loaded.png'});
const rows=await p.$$('tbody tr'); const row=rows[9];await row.screenshot({path:dir+'row.png'});
const table=await p.$('table');await table.screenshot({path:dir+'table.png'});
await writeFile(dir+'capture.json',JSON.stringify({url:'http://localhost:8770/app/',text:await p.evaluate(()=>document.body.innerText),row:await row.boundingBox(),table:await table.boundingBox(),capturedAt:new Date().toISOString()},null,2));
console.log('Captured real landing, empty input, loaded workspace, and live results.');await browser.close();
